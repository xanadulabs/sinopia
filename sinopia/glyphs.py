"""A 5-by-7 pixel alphabet. Upper case, digits, space, and a period."""

ADVANCE = 6
HEIGHT = 7


def _glyph(*rows: str) -> tuple[int, ...]:
    if len(rows) != HEIGHT or any(len(row) != 5 or set(row) - {"0", "1"} for row in rows):
        raise ValueError("a glyph is seven rows of five bits")
    return tuple(int(row, 2) for row in rows)


